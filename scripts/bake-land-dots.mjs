/**
 * Bakes a lat/lon land grid into src/data/landDots.js.
 *
 * Run once at author time (npm run bake:land). The site ships the generated
 * array, so world-atlas/topojson stay devDependencies and the browser never
 * downloads or parses topology.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import * as topojson from 'topojson-client';

const require = createRequire(import.meta.url);
const topo = require('world-atlas/land-110m.json');
const land = topojson.feature(topo, topo.objects.land);

// Ray casting against one ring.
function inRing(lon, lat, ring) {
  let hit = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}
function onLand(lon, lat) {
  for (const f of land.features) {
    const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
    for (const poly of polys) {
      if (!inRing(lon, lat, poly[0])) continue;
      let hole = false;
      for (let h = 1; h < poly.length; h++) if (inRing(lon, lat, poly[h])) { hole = true; break; }
      if (!hole) return true;
    }
  }
  return false;
}

// Equal-area-ish sampling: rows spaced evenly in latitude, columns scaled by
// cos(lat) so the poles don't collect a dense smear of dots.
const STEP = 2.2;
const dots = [];
for (let lat = -84; lat <= 84; lat += STEP) {
  const cols = Math.max(6, Math.round((360 / STEP) * Math.cos((lat * Math.PI) / 180)));
  for (let c = 0; c < cols; c++) {
    const lon = -180 + (360 / cols) * c;
    if (onLand(lon, lat)) dots.push([+lat.toFixed(2), +lon.toFixed(2)]);
  }
}

writeFileSync('src/data/landDots.js',
`// GENERATED by scripts/bake-land-dots.mjs — do not edit by hand.
// Land sample points [lat, lon] from Natural Earth 110m via world-atlas (public domain).
export const LAND_DOTS = ${JSON.stringify(dots)};
`);
console.log(`${dots.length} land dots -> src/data/landDots.js`);
